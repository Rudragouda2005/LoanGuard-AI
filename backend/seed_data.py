def seed_initial_applications_if_empty() -> None:
    """Populate SQLite with realistic demo records scored by the real ML & consistency engines."""
    if get_application_count() > 0:
        return

    for idx, item in enumerate(INITIAL_SEED_APPLICATIONS, start=1):
        ml_res = predict_application(item)
        checks = run_consistency_checks(item)

        applicant_record = {
            "applicant_id": f"APP-{1000 + idx}",
            "name": item["applicant_name"],
            "age": item["age"],
            "employment_type": item["employment_type"],
            "monthly_income": item["monthly_income"],
            "marital_status": item.get("marital_status", "Single"),
            "education": item.get("education", "Graduate"),
            "dependents": item.get("dependents", 0),
        }

        application_record = {
            "application_id": item["application_id"],
            "applicant_id": applicant_record["applicant_id"],
            "loan_amount": item["loan_amount"],
            "loan_purpose": item["loan_purpose"],
            "loan_term": item["loan_term"],
            "fraud_score": ml_res["fraud_score"],
            "risk_level": ml_res["risk_level"],
            "prediction": ml_res["prediction"],
            "application_date": item["application_date"],
            "investigation_status": item["investigation_status"],
            "employer_name": item["employer_name"],
            "years_of_employment": item["years_of_employment"],
            "employment_verification": item["employment_verification"],
            "existing_debt": item["existing_debt"],
            "credit_history": item["credit_history"],
            "declared_annual_income": item["declared_annual_income"],
            "bank_verification": item["bank_verification"],
            "previous_loan_history": item["previous_loan_history"],
            "document_verification": item["document_verification"],
            "declared_employment_info": item["declared_employment_info"],
            "notes": item["notes"],
            "is_demo": True,
        }

        save_application_record(
            applicant=applicant_record,
            application=application_record,
            explanations=ml_res["explanations"],
            checks=checks,
        )
